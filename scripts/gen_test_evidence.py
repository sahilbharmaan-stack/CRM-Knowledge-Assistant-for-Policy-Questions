"""Runs tests/test_questions.json with the mock provider and writes docs/TEST_EVIDENCE.md."""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ["LLM_PROVIDER"] = "mock"
os.environ.pop("GEMINI_API_KEY", None)
from backend import db, pipeline  # noqa: E402
from backend.bootstrap import bootstrap  # noqa: E402

conn = db.connect(":memory:")
bootstrap(conn)
user = dict(db.get_user_by_username(conn, "counsellor1"))
rows = []
for c in json.loads((ROOT / "tests" / "test_questions.json").read_text(encoding="utf-8")):
    if c["type"] == "real_llm_only":
        rows.append((c["id"], c["type"], c["question"], "abstain with a real LLM", "not run offline (live demo)", "SKIP")); continue
    r = pipeline.ask(conn, user, c["question"], "gemini" if c["type"] == "api_failure" else "mock")
    cit = r["citations"][0] if r.get("citations") else None
    actual = r["status"] + (f" -> {cit['doc_code']} v{cit['version']} / {cit['heading']}" if cit else "")
    exp = {"answer": f"answered -> {c.get('expect_doc')} v{c.get('expect_version')} / {c.get('expect_heading') or 'any section'}",
           "abstain": "abstained, no citations", "reject": "rejected", "api_failure": "api_error, passages shown",
           "old_version": "only v2.1 cited, never retired v1.0", "unsupported_action": "stays pending_review, nothing approved",
           "injection": "answered/abstained, pending_review"}[c["type"]]
    ok = "PASS"
    if c["type"] == "answer": ok = "PASS" if cit and cit["doc_code"] == c["expect_doc"] else "FAIL"
    if c["type"] == "abstain": ok = "PASS" if r["status"] == "abstained" else "FAIL"
    if c["type"] == "reject": ok = "PASS" if r["status"] == "rejected" else "FAIL"
    if c["type"] == "api_failure": ok = "PASS" if r["status"] == "api_error" and r["passages"] else "FAIL"
    rows.append((c["id"], c["type"], c["question"] or "(empty)", exp, actual, ok))
lines = ["# Test evidence (offline mock provider)", "",
         "Generated by `scripts/gen_test_evidence.py`. Q22 is checked live with Gemini during the demo.", "",
         "| ID | Type | Input | Expected | Actual | Result |", "|---|---|---|---|---|---|"]
lines += [f"| {a} | {b} | {c.strip() or '(blank)'} | {d} | {e} | {f} |" for a, b, c, d, e, f in rows]
(ROOT / "docs" / "TEST_EVIDENCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(sum(r[5] == "PASS" for r in rows), "pass of", len(rows))
